/// Supported UI languages for the Student Portal.
/// To add a new language later:
/// 1) Add an enum value here, and
/// 2) Add its key->text map inside [_translations] below.
enum PortalLocale {
  en('en', 'English', 'EN'),
  ru('ru', 'Русский', 'RU'),
  ky('ky', 'Кыргызча', 'KG'),
  kk('kk', 'Қазақша', 'KZ'),
  uz('uz', 'Oʻzbekcha', 'UZ'),
  zh('zh', '中文', '中文');

  const PortalLocale(this.code, this.nativeName, this.shortTag);
  final String code;
  final String nativeName;
  final String shortTag;

  static PortalLocale fromCode(String? code) {
    return PortalLocale.values.firstWhere(
      (e) => e.code == code,
      orElse: () => PortalLocale.en,
    );
  }
}

class StudentPortalL10n {
  const StudentPortalL10n(this.locale);

  final PortalLocale locale;

  String text(String key, [Map<String, String> params = const {}]) {
    final table = _translations[locale] ?? _translations[PortalLocale.en]!;
    var value = table[key] ?? _translations[PortalLocale.en]![key] ?? key;
    for (final entry in params.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

  String weekdayShort(int weekday) {
    final list = _weekdays[locale] ?? _weekdays[PortalLocale.en]!;
    if (weekday < 1 || weekday > 7) return '';
    return list[weekday - 1];
  }

  String formatSchedule(StudyGroup group) {
    if (group.scheduleWeekdays.isEmpty) return text('flexibleSchedule');
    final sorted = [...group.scheduleWeekdays]..sort();
    final days = sorted.map(weekdayShort).join(', ');
    final hh = group.startHour.toString().padLeft(2, '0');
    final mm = group.startMinute.toString().padLeft(2, '0');
    return '$days • $hh:$mm (${group.durationMinutes} ${text('minShort')})';
  }

  String languageName(String code) {
    return switch (code) {
      'chinese' => text('langChinese'),
      'english' => text('langEnglish'),
      _ => code,
    };
  }

